import type { BlastingList, CategoryRecord, ShiftRecord } from "../types";
import { resolveItemCategory } from "./categories";
import { listToArray } from "./listItems";
import { shiftName } from "./shifts";

function download(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

function csvEscape(v: string): string {
  return v.includes(",") || v.includes('"') || v.includes("\n")
    ? `"${v.replace(/"/g, '""')}"`
    : v;
}

function categoryCounts(
  list: BlastingList,
  categories: CategoryRecord[],
): { name: string; count: number }[] {
  const counts = new Map<string, number>();
  for (const item of Object.values(list.items)) {
    const category = resolveItemCategory(item, categories);
    counts.set(category.name, (counts.get(category.name) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([name, count]) => ({ name, count }))
    .sort((a, b) => b.count - a.count);
}

export function exportCsv(
  list: BlastingList,
  categories: CategoryRecord[],
  shifts: ShiftRecord[] = [],
): void {
  const rows = listToArray(list);
  let csv = "Date,Shift,Category,Code,Added By\n";
  for (const item of rows) {
    csv += [
      list.date,
      csvEscape(shiftName(list.shift, shifts)),
      csvEscape(resolveItemCategory(item, categories).name),
      csvEscape(item.code),
      csvEscape(item.createdByName),
    ].join(",");
    csv += "\n";
  }
  const blob = new Blob(["\uFEFF" + csv], { type: "text/csv;charset=utf-8;" });
  download(blob, `BlastingList_${list.date}_${list.shift}.csv`);
}

export async function exportPdf(
  list: BlastingList,
  generatedBy: string,
  categories: CategoryRecord[],
  shifts: ShiftRecord[] = [],
): Promise<void> {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);
  const rows = listToArray(list);
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  doc.setFontSize(16);
  doc.text("Blasting Production Report", 40, 45);
  doc.setFontSize(10);
  doc.text(`Date: ${list.date}`, 40, 65);
  doc.text(`Shift: ${shiftName(list.shift, shifts)}`, 40, 79);
  doc.text(`Generated By: ${generatedBy}`, 40, 93);

  const counts = categoryCounts(list, categories);
  doc.setDrawColor(200);
  doc.setFillColor(245, 245, 245);
  doc.rect(390, 30, 165, 90, "F");
  doc.text("Summary:", 402, 50);
  doc.text(`Total Items: ${rows.length}`, 402, 66);
  counts.slice(0, 4).forEach((entry, index) => {
    doc.text(`${entry.name}: ${entry.count}`, 402, 82 + index * 12);
  });

  autoTable(doc, {
    startY: 130,
    head: [["#", "Category", "Code / Details", "Added By"]],
    body: rows.map((r, i) => [
      String(i + 1),
      resolveItemCategory(r, categories).name,
      r.code,
      r.createdByName || "—",
    ]),
    theme: "grid",
    headStyles: { fillColor: [40, 40, 40] },
    alternateRowStyles: { fillColor: [240, 240, 240] },
    styles: { fontSize: 9 },
    margin: { left: 40, right: 40 },
  });

  const pageHeight = doc.internal.pageSize.getHeight();
  const finalY = Math.min(
    pageHeight - 90,
    (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable
      ?.finalY ?? 200,
  );
  doc.text("_______________________", 380, finalY + 40);
  doc.text("Manager Signature", 390, finalY + 56);
  doc.setFontSize(8);
  doc.text(`Generated on: ${new Date().toLocaleString()}`, 40, pageHeight - 25);

  doc.save(`Report_${list.date}_${list.shift}.pdf`);
}

export function shareToWhatsApp(
  list: BlastingList,
  categories: CategoryRecord[],
  shifts: ShiftRecord[] = [],
): void {
  const rows = listToArray(list);
  let msg = `🏭 *Blasting List*\n📅 ${list.date} (${shiftName(list.shift, shifts)})\n\n`;
  for (const item of rows) {
    msg += `▪️ [${resolveItemCategory(item, categories).name}] ${item.code}\n`;
  }
  window.open(
    `https://wa.me/?text=${encodeURIComponent(msg)}`,
    "_blank",
    "noopener,noreferrer",
  );
}
